import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const read = file => readFile(resolve(root, file), 'utf8');
const [houses, logic, game] = await Promise.all([
  read('houses.mjs'), read('logic.mjs'), read('game.mjs')
]);

const dataCode = houses.replace(/^export /gm, '');
const logicCode = logic.replace(/^export /gm, '');
const gameCode = game.replace(/^import .*?;\r?\n/gm, '');
const bundle = `// Generated by build.mjs. Edit the .mjs source files, then run: node build.mjs\n(function () {\n'use strict';\n${dataCode}\n${logicCode}\n${gameCode}\n})();\n`;
await writeFile(resolve(root, 'standalone.js'), bundle, 'utf8');
console.log('Built standalone.js');
